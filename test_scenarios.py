#!/usr/bin/env python3
# Тестовые сценарии для бота

from bot_logic import MedicalBot

def run_scenario(name, messages, show_variations=False):
    """Запуск тестового сценария"""
    print(f"\n{'='*60}")
    print(f"📝 СЦЕНАРИЙ: {name}")
    print('='*60)
    
    bot = MedicalBot()
    print(f"\n🤖 Бот: {bot.get_greeting()}")
    
    for msg in messages:
        print(f"\n👤 Пациент: {msg}")
        response = bot.process_message(msg)
        print(f"🤖 Бот: {response}")
    
    print(f"\n{'='*60}\n")

def test_variations():
    """Тест разнообразия ответов"""
    print("\n" + "="*60)
    print("🎲 ТЕСТ РАЗНООБРАЗИЯ ОТВЕТОВ")
    print("="*60)
    
    # Тест приветствий
    print("\n--- Приветствия (5 раз) ---")
    bot = MedicalBot()
    for i in range(5):
        print(f"{i+1}. {bot.get_greeting()}")
    
    # Тест ответов на один и тот же вопрос
    print("\n--- Ответ на 'Сколько стоит МРТ?' (5 раз) ---")
    questions = [
        "Сколько стоит МРТ поясницы?",
        "МРТ поясничного отдела цена?",
        "Хочу МРТ поясницы",
        "Мрт поясницы сколько?",
        "Поясница мрт цена"
    ]
    
    for q in questions:
        bot = MedicalBot()
        response = bot.process_message(q)
        print(f"\n❓ {q}")
        print(f"🤖 {response[:200]}...")

def main():
    # Тест разнообразия
    test_variations()
    
